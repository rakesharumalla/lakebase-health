#!/usr/bin/env python3
"""Generate docs/CHECKS.md and the README checks summary from the check YAML files.

Usage (from anywhere; needs PyYAML, for example the engine venv):
    python scripts/gen_checks_doc.py           # rewrite docs/CHECKS.md and the README summary
    python scripts/gen_checks_doc.py --check   # exit 1 if either file is out of date

The README summary sits between the CHECKS_START and CHECKS_END marker comments. Whether the fixer can run a
fix is decided by the fixer's own allowlist (engine/src/lakebase_health/fixer/allowlist.py), loaded by path so
the doc and the fixer cannot disagree.
"""
import argparse
import importlib.util
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CHECKS_DIR = ROOT / "engine" / "src" / "lakebase_health" / "checks"
ALLOWLIST = ROOT / "engine" / "src" / "lakebase_health" / "fixer" / "allowlist.py"
CHECKS_MD = ROOT / "docs" / "CHECKS.md"
README = ROOT / "README.md"
START = "<!-- CHECKS_START: generated by scripts/gen_checks_doc.py; do not edit by hand -->"
END = "<!-- CHECKS_END -->"

SOURCE_LABEL = {"delta": "telemetry", "postgres": "postgres", "api": "api"}
SOURCE_ORDER = ("delta", "postgres", "api")
CATEGORY_ORDER = ("incidents", "performance", "capacity", "indexing", "maintenance", "forecast", "replication",
                  "connectivity", "throughput", "config", "schema", "security", "backup")
SEVERITIES = ("info", "warning", "critical")
ACTIONABLE = {"ddl", "setting"}  # mirrors checkspec.ACTIONABLE_KINDS
VAR_RE = re.compile(r"\{([a-z_]+)\}")
# Placeholders that hold a whole statement, filled with a representative value; any other one is an identifier
SAMPLE = {"index_def_concurrently": "CREATE INDEX CONCURRENTLY x ON x USING btree (x)"}
TABLE_RE = re.compile(r"system\.lakebase\.([a-z_]+)")


def load_allowlist():
    spec = importlib.util.spec_from_file_location("lbh_allowlist", ALLOWLIST)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def load_checks() -> list:
    checks = []
    for path in sorted(CHECKS_DIR.rglob("*.yaml")):
        if path.name == "exclusions.yaml":
            continue
        checks.append(yaml.safe_load(path.read_text()))

    def key(c):
        cat = c["category"]
        return (CATEGORY_ORDER.index(cat) if cat in CATEGORY_ORDER else len(CATEGORY_ORDER), cat,
                SOURCE_ORDER.index(c["source"]), c["id"])
    return sorted(checks, key=key)


def prose(text) -> str:
    """One paragraph of Markdown-safe text from a YAML scalar."""
    out = " ".join(str(text or "").split())
    return out.replace("\\", "\\\\").replace("*", "\\*").replace("<", "&lt;").replace("|", "\\|")


def number(v) -> str:
    v = float(v)
    for unit, size in (("TiB", 1024 ** 4), ("GiB", 1024 ** 3), ("MiB", 1024 ** 2)):
        if abs(v) >= size and v % size == 0:
            return f"{int(v // size)} {unit}"
    if v.is_integer():
        return f"{int(v):,}"
    return f"{v:g}"


def thresholds(c) -> str:
    op = "<" if c.get("direction", "above") == "below" else ">"
    t = c["thresholds"]
    return "; ".join(f"{s} when measure {op} {number(t[s])}" for s in SEVERITIES if s in t)


def severities(c) -> str:
    return " / ".join(s for s in SEVERITIES if s in c["thresholds"])


def allowed(allowlist, template) -> bool:
    """Whether the fixer's allowlist accepts the template, with every placeholder filled by an identifier."""
    if not template:
        return False
    try:
        allowlist.parse(VAR_RE.sub(lambda m: SAMPLE.get(m.group(1), "x"), template))
        return True
    except allowlist.NotAllowed:
        return False


def rollback_note(fix) -> str:
    return re.sub(r"^not needed:\s*", "", str(fix.get("rollback_note") or "nothing to undo"), flags=re.I)


def fixer_status(c, allowlist) -> tuple:
    """(short label for the summary, sentence for CHECKS.md)."""
    fix = c.get("fix")
    if not fix:
        return "-", "No candidate fix; the finding is information only."
    kind = fix.get("kind")
    actionable = kind in ACTIONABLE and bool(fix.get("reversible")) and bool(fix.get("template"))
    if not actionable:
        return "-", "Guidance only (`manual`). The app shows it as text; nothing is proposed to the fixer."
    by_hand = ("`CREATE INDEX CONCURRENTLY`, `DROP INDEX CONCURRENTLY`, `ANALYZE` and `ALTER TABLE ... SET|RESET "
               "(autovacuum_*)` are accepted). The app shows the SQL marked \"apply by hand\".")
    if not allowed(allowlist, fix["template"]):
        return "by hand", "No action is proposed: the statement is outside the fixer allowlist (only " + by_hand
    if fix.get("rollback") and not allowed(allowlist, fix["rollback"]):
        return "by hand", "No action is proposed: the rollback is outside the fixer allowlist (only " + by_hand
    if fix.get("verify_on_branch"):
        text = "Yes: verify on a branch, then apply after a second approval."
        label = "verify + apply"
    else:
        text = "Yes: apply after approval. Not verifiable on a branch (no measurable query effect)."
        label = "apply"
    if not fix.get("rollback"):
        text += f" Rollback: not needed ({rollback_note(fix)})."
    return label, text


def source_detail(c) -> str:
    src = c["source"]
    if src == "delta":
        tables = sorted(set(TABLE_RE.findall(c.get("sql") or "")))
        reads = ", ".join(f"`system.lakebase.{t}`" for t in tables) if tables else "`system.lakebase`"
        return f"telemetry: {reads}, read from the `raw_*` copy"
    if src == "postgres":
        scope = "once per endpoint (instance-wide catalogs)" if c.get("per_database") is False else "in every database"
        return f"postgres: catalog query on the running read-write compute, {scope}"
    return f"api: Lakebase API inventory (`{c.get('function')}`)"


def enrolment(c) -> str:
    if c["source"] == "postgres":
        return "Yes: a Postgres role for the engine SP with `pg_monitor` on the branch"
    if c["source"] == "api":
        return "No (the engine SP needs `CAN_USE` on the project)"
    return "No"


def code_block(text, lang) -> list:
    return [f"```{lang}", str(text).strip(), "```"]


def check_section(c, allowlist) -> list:
    rows = [("Category", c["category"]), ("Source", source_detail(c)), ("Needs enrolment", enrolment(c)),
            ("Thresholds", thresholds(c))]
    if c.get("schedule") == "daily":
        rows.append(("Schedule", "once a day (reads pages; bounded)"))
    if c.get("requires_extension"):
        rows.append(("Requires extension", f"`{c['requires_extension']}` (skipped as `extension_missing` without it)"))
    if c.get("guards"):
        rows.append(("Confidence", "low unless " + " and ".join(f"`{g}`" for g in c["guards"])))
    if c.get("replica_check") == "intersect":
        rows.append(("Read replicas", "reported only when every active, enrolled read replica of the branch "
                                      "also reports the object"))
    if c.get("query_scoped"):
        rows.append(("Query scope", "platform, engine and fixer roles are filtered out; one finding per query"))
    sb = c.get("superseded_by")
    if sb:
        names = ", ".join(f"[`{x}`](#{x})" for x in sb["checks"])
        rows.append(("Superseded by", f"{names} (same {sb['key']}, while that finding is open and at least as "
                                      "severe)"))
    out = [f'<a id="{c["id"]}"></a>', "", f"### {c['id']}", "", f"**{prose(c['title'])}**", "",
           "| | |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in rows]
    out += ["", f"**What it means.** {prose(c['explain'])}", ""]
    fix = c.get("fix")
    if fix:
        flags = [f"kind `{fix.get('kind')}`", f"risk `{fix.get('risk')}`"]
        if fix.get("kind") in ACTIONABLE:
            flags.append("reversible" if fix.get("reversible") else "not reversible")
            flags.append("verified on a branch" if fix.get("verify_on_branch") else "not verified on a branch")
        out += [f"**Candidate fix** ({', '.join(flags)}):", ""]
        if fix.get("template"):
            out += code_block(fix["template"], "sql" if fix.get("kind") in ACTIONABLE else "text") + [""]
        else:
            out += ["See the explanation above; there is no SQL for this one.", ""]
        if fix.get("rollback"):
            out += ["Rollback:", ""] + code_block(fix["rollback"], "sql") + [""]
        elif fix.get("rollback_note"):
            out += [f"Rollback: not needed — {rollback_note(fix)}.", ""]
    out += [f"**Fixer.** {fixer_status(c, allowlist)[1]}", ""]
    return out


def checks_md(checks, allowlist) -> str:
    by_source = {s: sum(1 for c in checks if c["source"] == s) for s in SOURCE_ORDER}
    out = [
        "# Lakebase Health checks",
        "",
        "<!-- Generated by scripts/gen_checks_doc.py from engine/src/lakebase_health/checks/**/*.yaml. "
        "Do not edit by hand. -->",
        "",
        f"{len(checks)} checks: {by_source['delta']} telemetry, {by_source['postgres']} Postgres and "
        f"{by_source['api']} API. The tested SQL and the reasoning behind each threshold are in "
        "[HEALTH_CHECKS.md](../HEALTH_CHECKS.md); this page is generated from the check files the engine runs.",
        "",
        "## How to read this page",
        "",
        "| Term | Meaning |",
        "|---|---|",
        "| Source | `telemetry`: SQL over the Delta copy of `system.lakebase` (all projects, no setup). `postgres`: "
        "SQL over the Postgres catalog on a running, enrolled read-write compute (never wakes a suspended "
        "compute). `api`: settings read from the Lakebase API. |",
        "| Thresholds | Each check computes one number per object (the measure). The highest severity whose "
        "threshold the measure passes (strictly greater, or strictly less for checks where low is bad) is the "
        "finding's severity. No threshold passed means no finding. |",
        "| Needs enrolment | Postgres checks run only on branches where the engine SP has a Postgres role "
        "(see the README, \"Enroll a project for Postgres checks\"). |",
        "| Confidence | `low` when a guard fails, for example when the statistics window is shorter than 24 "
        "hours. |",
        "| Superseded by | While a more specific finding is open for the same object, database or endpoint, "
        "this one is not reported (status `superseded`). It comes back if the other finding resolves. |",
        "| Candidate fix | Placeholders in braces are filled from the finding's row; `{index_def_concurrently}` is "
        "the index definition (`pg_get_indexdef`) with `CONCURRENTLY` after `INDEX`. `ddl` and `setting` fixes "
        "become proposed actions when the fixer allowlist accepts the statement and its rollback; a fix with "
        "nothing to undo has a rollback note instead of a rollback. `manual` fixes are guidance only. |",
        "| Fixer | Whether the fixer job can run the proposed action after approval. |",
        "",
        "## Contents",
        "",
    ]
    cats = []
    for c in checks:
        if c["category"] not in cats:
            cats.append(c["category"])
    for cat in cats:
        ids = [c["id"] for c in checks if c["category"] == cat]
        out.append(f"- **{cat}**: " + ", ".join(f"[`{i}`](#{i})" for i in ids))
    out.append("")
    for cat in cats:
        out += [f"## {cat.capitalize()}", ""]
        for c in checks:
            if c["category"] == cat:
                out += check_section(c, allowlist)
    return "\n".join(out).rstrip() + "\n"


def summary(checks, allowlist) -> str:
    out = [START, "",
           f"{len(checks)} checks. Full explanations, thresholds and fixes: [docs/CHECKS.md](docs/CHECKS.md).", "",
           "| Area | Check | What it finds | Source | Severities | Fixer |",
           "|---|---|---|---|---|---|"]
    last = None
    for c in checks:
        area = c["category"] if c["category"] != last else ""
        last = c["category"]
        out.append(f"| {area} | [`{c['id']}`](docs/CHECKS.md#{c['id']}) | {prose(c['title'])} | "
                   f"{SOURCE_LABEL[c['source']]} | {severities(c)} | {fixer_status(c, allowlist)[0]} |")
    out += ["", "Fixer: `verify + apply` = verified on a branch, then applied; `apply` = applied after approval "
            "without branch verification; `by hand` = outside the fixer allowlist, so no action is proposed (the app "
            "shows the SQL to run yourself); "
            "`-` = guidance only.", "", END]
    return "\n".join(out)


def with_summary(readme: str, block: str) -> str:
    if START not in readme or END not in readme:
        raise SystemExit(f"README.md has no {START!r} ... {END!r} markers")
    head, rest = readme.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the generated files are out of date")
    a = ap.parse_args(argv)
    allowlist = load_allowlist()
    checks = load_checks()
    want_md = checks_md(checks, allowlist)
    want_readme = with_summary(README.read_text(), summary(checks, allowlist))
    stale = [p for p, want in ((CHECKS_MD, want_md), (README, want_readme))
             if not p.exists() or p.read_text() != want]
    if a.check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)} (run scripts/gen_checks_doc.py)", file=sys.stderr)
        return 1 if stale else 0
    CHECKS_MD.parent.mkdir(parents=True, exist_ok=True)
    CHECKS_MD.write_text(want_md)
    README.write_text(want_readme)
    print(f"{len(checks)} checks: wrote {CHECKS_MD.relative_to(ROOT)} and the README summary")
    return 0


if __name__ == "__main__":
    sys.exit(main())
